#!/usr/bin/env python3
"""Build (or --check) the SYNTHETIC seed golden set in golden/synthetic/.

Every clip is generated by the simulator (oiris.adapters.sim): no sensor recording, no person,
no third-party data. Source tier "synthetic". It exercises the C5 manifest, replay and
expectation tooling end to end; it is NOT evidence that anything works on real objects.
Real data follows golden/README.md (own recordings, consent IDs, encrypted archive outside git).

  python scripts/make_synthetic_golden.py          # (re)build clips, manifest, expectations
  python scripts/make_synthetic_golden.py --check  # verify hashes + replay == expectations
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from oiris.headless import record_clip, run_replay  # noqa: E402
from oiris.modules.golden import Clip, Manifest, sha256_file  # noqa: E402

OUT = ROOT / "golden" / "synthetic"
# scenario -> (label, split); one test clip per class family, frozen
SEED = {"quiet": ("benign", "test"), "camera_lens": ("camera_device", "test"), "warm_prop": ("warm_object", "test"),
        "replay_screen": ("screen_replay", "test"), "fixed_emitter_drift": ("fixed_emitter", "test")}
STEPS = 3


def summary(res: list[dict]) -> dict:
    last = res[-1]
    return {"level": last["level"], "signatures": sorted(last["signatures"]), "anomaly_index": round(last["anomaly_index"], 4),
            "suppressed": last["suppressed"]}


def build() -> Manifest:
    m = Manifest()
    exp = {}
    for scen, (label, split) in SEED.items():
        d = OUT / "clips" / scen
        record_clip(scen, d, STEPS, seed=0)
        for f in sorted(d.iterdir()):
            m.add(Clip(f"syn-{scen}-{f.stem}", str(f.relative_to(OUT)), sha256_file(f), label, split, "synthetic", rights="generated"))
        exp[scen] = summary(run_replay(d, None))
    m.freeze()
    m.save(OUT / "manifest.json")
    (OUT / "expected.json").write_text(json.dumps(exp, indent=1, sort_keys=True), encoding="utf-8")
    return m


def check() -> list[str]:
    m = Manifest.load(OUT / "manifest.json")
    bad = m.verify(OUT)
    if any(c.source_tier != "synthetic" or c.contains_person for c in m.clips):
        bad.append("<non-synthetic or person clip in the synthetic set>")
    exp = json.loads((OUT / "expected.json").read_text(encoding="utf-8"))
    for scen in SEED:
        got = summary(run_replay(OUT / "clips" / scen, None))
        e = exp[scen]
        if (got["level"], got["signatures"], got["suppressed"]) != (e["level"], e["signatures"], e["suppressed"]) \
                or abs(got["anomaly_index"] - e["anomaly_index"]) > 1e-3:
            bad.append(f"{scen}: {got} != {e}")
    return bad


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        b = check()
        print("synthetic golden: PASS" if not b else f"synthetic golden: FAIL {b}")
        sys.exit(1 if b else 0)
    m = build()
    print(f"built {len(m.clips)} synthetic clip files, frozen test hash {m.frozen_test_hash}")
